export function getTranslation(lang: SupportedLanguage, key: keyof typeof translations['ru'], params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.ru;
  let text = (dict as Record<string, string>)[key] || translations.ru[key] || key;
  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }
  return text;
}
